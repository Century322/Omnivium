class LocaleProvider extends ChangeNotifier {
  Locale _locale = const Locale('zh');
  Locale get locale => _locale;
  Map<String, String>? _cachedMap;
  Locale? _cachedLocale;

  LocaleProvider() {
    _load();
  }

  Future<void> _load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString('omnivium_locale') ?? 'zh';
    _locale = Locale(saved);
    notifyListeners();
  }

  Future<void> setLocale(Locale locale) async {
    _locale = locale;
    _cachedMap = null;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('omnivium_locale', locale.languageCode);
    notifyListeners();
  }

  void setLocaleFromLabel(String labelOrCode) {
    switch (labelOrCode) {
      case 'en':
      case 'English':
        setLocale(const Locale('en'));
        break;
      case 'ja':
      case '日本語':
        setLocale(const Locale('ja'));
        break;
      case 'ko':
      case '한국어':
        setLocale(const Locale('ko'));
        break;
      default:
        setLocale(const Locale('zh'));
    }
  }

  String get currentLabel {
    switch (_locale.languageCode) {
      case 'en':
        return 'English';
      case 'ja':
        return '日本語';
      case 'ko':
        return '한국어';
      default:
        return '中文';
    }
  }

  S get _s => lookupS(_locale);

  String t(String key) {
    try {
      if (_cachedMap != null && _cachedLocale == _locale) {
        return _cachedMap![key] ?? key;
      }
      final s = _s;
      _cachedMap = _buildMap(s);
      _cachedLocale = _locale;
      return _cachedMap![key] ?? key;
    } catch (_) {
      return key;
    }
  }

